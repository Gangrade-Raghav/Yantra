5. Percentage Error and Standard Values
Where Yantra displays a percentage error by comparing your result to a standard value, this comparison is provided as an educational tool to help you understand the concept of experimental error. The standard values used are accepted scientific constants. The percentage error is a measure of how close your phone's sensors came to the accepted value — it is not a quality score or a pass/fail indicator.

A percentage error of 5-15% is typical and acceptable for the class of instrument being used. A very low percentage error does not mean your data is more accurate — it may mean your particular sensor unit happens to be well-calibrated, or that random errors cancelled out. A higher percentage error is a learning opportunity to identify sources of error, not a failure.
6. Heart Rate Measurements
The heart rate measurement experiment uses photoplethysmography (PPG) — the detection of blood flow through the finger using the phone camera and flash. This technique is used in commercial fitness wearables but in those devices is implemented with dedicated optical hardware and algorithms.

Yantra's implementation using a standard phone camera is less accurate than dedicated medical devices. The heart rate values produced by Yantra's heart rate experiment are approximate and should be treated as educational demonstrations of the PPG principle. They must not be used for medical assessment of any kind. If you have any concern about your cardiovascular health, consult a qualified medical professional.
