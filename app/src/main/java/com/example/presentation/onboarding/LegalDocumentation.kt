DOCUMENT 4 — SCIENTIFIC ACCURACY DISCLAIMER
Effective Date: 1 June 2026

1. Nature of Phone Sensor Data
Yantra uses the built-in sensors of consumer Android smartphones to collect experimental data. These sensors — accelerometers, gyroscopes, magnetometers, microphones, cameras, GPS receivers, and light sensors — are manufactured for general consumer use. They are not calibrated scientific instruments. They are not subject to metrology standards. Their accuracy, precision, and reliability vary significantly between devices, manufacturers, hardware generations, and individual units.
2. Known Sources of Error
Data collected through Yantra experiments is subject to the following known sources of error. This list is not exhaustive:
* Sensor manufacturing tolerance: variation between individual sensor units of the same model
* Temperature sensitivity: sensor readings shift with device temperature
* Magnetic interference: the phone's own electronic components interfere with magnetometer readings
* Vibration noise: ambient vibration contaminates accelerometer and gyroscope data
* Sampling rate limitations: consumer sensors sample at fixed rates that may not capture fast-changing phenomena accurately
* Quantisation error: digital sensors have finite resolution
* User technique variation: how the student performs the physical experiment affects results
* Environmental factors: humidity, air pressure, electromagnetic interference, and ambient light affect various sensors
* Physical setup imprecision: measurements of lengths, heights, and distances made by the student introduce additional error
* Filtering artefacts: the digital filters applied to raw sensor data to reduce noise may introduce phase lag or smooth out real phenomena
3. What the Results Are Good For
Despite the above limitations, Yantra experimental results are genuinely useful for:
* Understanding scientific concepts through personal, hands-on experience
* Learning experimental methodology — hypothesis, setup, data collection, analysis, conclusion
* Producing results in the correct order of magnitude for standard physical constants
* Observing qualitative relationships between variables (e.g., that longer pendulums have longer periods)
* Generating authentic, data-backed practical files for school submission
* Developing intuition for measurement error and its sources
